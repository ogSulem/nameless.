def days_label(days: int) -> str:
    """«30 дней» reads like a contract; «месяц» reads like a gift."""
    if days % 30 == 0 and days >= 30:
        months = days // 30
        if months == 1:
            return "месяц"
        if months < 12:
            return f"{months} мес."
    if days == 7:
        return "неделя"
    return f"{days} дн."


